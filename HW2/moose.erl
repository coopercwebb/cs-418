data({random, N, P1, P2}) ->
  lists:flatten(
    [ [    case rand:uniform() < P1 of
	     true -> might_be_a_moose("moose", P2);
	     false ->
	       case rand:uniform(96) of
		 NL when NL >= 96 -> $\n;
		 V -> 31+V
	       end
	   end
	|| _ <- lists:seq(1, N) ], $\n]).

might_be_a_moose([], _) -> [];
might_be_a_moose([Hd | Tl], P) ->
  case rand:uniform() < P of
    true -> [];
    false -> [Hd | might_be_a_moose(Tl, P)]
  end.

