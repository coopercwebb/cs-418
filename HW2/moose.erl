      "The earliest known species in the moose lineage is Libralces gallicus,",
      "which lived in the Pliocene-Early Pleistocene.[151] Libralces gallicus",
      "came from the warm savannas of Pliocene Europe, with the best-preserved",
      "skeletons being found in southern France. L. gallicus was 1.25 times",
      "larger than the Alaskan moose in linear dimensions, making it nearly",
      "twice as massive. L. gallicus had many striking differences from its",
      "modern descendants. It had a longer, narrower snout and a less-developed",
      "nasal cavity, more resembling that of a modern deer, lacking any sign of",
      "the modern moose-snout. Its face resembled that of the modern wapiti.",
      "However, the rest of its skull structure, skeletal structure and teeth",
      "bore strong resemblance to those features that are unmistakable in",
      "modern moose, indicating a similar diet. Its antlers consisted of a",
      "horizontal bar 2.5 m (8 ft 2 in) long, with no tines, ending in small",
      "palmations. Its skull and neck structure suggest an animal that fought",
      "using high-speed impacts, much like the Dall sheep, rather than locking",
      "and twisting antlers the way modern moose combat. Their long legs and",
      "bone structure suggest an animal that was adapted to running at high",
      "speeds over rough terrain.[153][154]",
      "",
      "Libralces gallicus was followed by Cervalces carnutorum during the first",
      "half of the Early Pleistocene. Cervalces carnutorum was soon followed by",
      "a much larger species called Cervalces latifrons (broad-fronted",
      "stag-moose), which first appeared during the late Early",
      "Pleistocene.[155] Many fossils of Cervalces latifrons have been found",
      "across Eurasia. Like its descendants, it inhabited mostly northern",
      "latitudes, and was probably well-adapted to the cold. C. latifrons was",
      "the largest deer known to have ever existed, standing more than 2.1 m (6",
      "ft 11 in) tall at the shoulders. This is bigger than even the Irish elk,",
      "which was 1.8 m (5 ft 11 in) tall at the shoulders. Its antlers were",
      "smaller than the Irish elk's, but comparable in size to those of L.",
      "gallicus. However, the antlers had a shorter horizontal bar and larger",
      "palmations, more resembling those of a modern moose.[153][154][156]",
      "Probably sometime in the Middle Pleistocene, Cervalces latifrons",
      "migrated into North America, giving rise to the stag moose (Cervalces",
      "scotti).[152] The modern moose is thought to have evolved from Cervalces",
      "latifrons at around the end of the Middle Pleistocene to the beginning",
      "of the Late Pleistocene, probably somewhere in East Asia, with the",
      "earliest fossils of the species in Europe dating to the early Late",
      "Pleistocene. The modern moose only arrived in North America around",
      "15,000 years ago, at the end of the Late Pleistocene.[157]",
